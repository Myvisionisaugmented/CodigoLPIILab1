def list_files_in_directory(directorio):
  retorno_dict = {
      "directorio": DIRECTORIO,
      "inventario":None,
      "archivos_procesados": []
  }

  try:
        archivos = os.listdir(directorio)
        abrir_archivo = os.path.join(directorio, 'inventario.json')

        if os.path.exists(abrir_archivo):
          tamaño = os.path.getsize(abrir_archivo)
          fecha_cambio = os.path.getmtime(abrir_archivo)
          fecha_cambio = datetime.fromtimestamp(fecha_cambio).strftime('%Y-%m-%d %H:%M:%S')

          with open(abrir_archivo, 'r', encoding='utf-8') as archivo:
            lista_contenido = json.load(archivo)
            if isinstance(lista_contenido, list):
              retorno_dict["inventario"] = lista_contenido
            else:
              print("El archivo 'inventario.json' no contiene una lista.")
        else:
          print("El archivo 'inventario.json' no existe.")

        return retorno_dict

  except FileNotFoundError:
        print('Directorio no encontrado.')
        return None

