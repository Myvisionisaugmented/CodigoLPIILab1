def buscador(inventario, termino_busqueda, columna_orden='producto'):
  try:
    ordenamiento = sorted(inventario, key=lambda x: x[columna_orden])
    print(f"[Proceso] Ordenamiento por columna aplicado. Order By: '{columna_orden}'")

    resultados = []
    termino = str(termino_busqueda).lower().strip()

    if termino:
      for item in ordenamiento:
        if any(termino in str(valor).lower() for valor in item.values()):
          resultados.append(item)

    return resultados, ordenamiento, columna_orden
  except Exception as e:
    print(f"Error en el ordenamiento': {e}")
    return [], inventario, columna_orden

